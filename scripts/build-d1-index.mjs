#!/usr/bin/env node
// Generate workers/semantic-search/d1-seed.sql containing INSERT statements
// for every artwork in public/data. After running this, deploy to D1 with:
//   npx wrangler d1 execute armin-text-search --file=./d1-seed.sql --remote
//
// (Use --remote so it lands in the production D1 that the deployed worker
// reads. Omit --remote to only update local dev D1.)
//
// 600K rows is well under D1's row count limit; the seed file is ~150-200MB
// of SQL but wrangler streams it. Expect 5-15 minutes for the remote load.

import fs from 'node:fs';
import path from 'node:path';

const REPO_ROOT = path.resolve(new URL('..', import.meta.url).pathname);
const DATA_DIR = path.join(REPO_ROOT, 'public', 'data');
const OUT_SQL = path.join(REPO_ROOT, 'workers', 'semantic-search', 'd1-seed.sql');
// D1 has a per-statement size limit (SQLITE_TOOBIG triggered around the
// 875th 200-row batch when a long-field row pushed the statement past
// the cap). Smaller batches + per-field truncation keep us well clear.
const BATCH = 50;
const MAX_FIELD_LEN = 1000; // truncate any single string field above this

function escapeSqlString(value) {
  if (value == null) return "''";
  let str = String(value);
  if (str.length > MAX_FIELD_LEN) str = str.slice(0, MAX_FIELD_LEN);
  return "'" + str.replace(/'/g, "''") + "'";
}

function pickFields(item, defaults) {
  return {
    id: String(item?.id || item?.semanticId || item?.semantic_id || '').trim(),
    name: String(item?.title || item?.name || item?.n || '').trim(),
    artist: String(item?.artist || item?.creator || item?.a || '').trim(),
    museum: String(item?.museum || item?.museumName || item?.m || defaults.museum || '').trim(),
    exhibition_id: String(item?.exhibitionId || item?.exhibition_id || item?.e || defaults.exhibition_id || '').trim(),
    image: String(item?.image || item?.imageUrl || item?.image_url || item?.i || '').trim(),
    date: String(item?.year || item?.date || item?.d || '').trim(),
    source_url: String(item?.sourceUrl || item?.source_url || item?.url || item?.u || item?.detailUrl || '').trim(),
    category: String(item?.category || item?.medium || item?.c || '').trim(),
  };
}

function loadCollection(filePath) {
  let raw;
  try { raw = fs.readFileSync(filePath, 'utf8'); }
  catch { return []; }

  let data;
  try { data = JSON.parse(raw); }
  catch (parseErr) {
    const idx = raw.indexOf('}{');
    if (idx > -1) {
      try { data = JSON.parse(raw.slice(idx + 1)); }
      catch { return []; }
    } else { return []; }
  }

  const arr = Array.isArray(data) ? data : (data.objects || data.items || data.artworks || data.collection || []);
  if (!Array.isArray(arr)) return [];

  // Try to derive defaults (museum name, exhibition id) from the file
  const defaults = {
    museum: data?.galleryName || data?.museum || '',
    exhibition_id: data?.galleryId || data?.exhibitionId || path.basename(filePath, '.json'),
  };

  return arr.map((item) => pickFields(item, defaults));
}

function main() {
  const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.json') && f.includes('collection'));
  // Also catch -gac.json, museum-named-after-museum.json, etc., that exhibitions.js references but don't end in -collection.json
  const referenced = (() => {
    try {
      const exh = fs.readFileSync(path.join(REPO_ROOT, 'src', 'data', 'exhibitions.js'), 'utf8');
      const matches = [...exh.matchAll(/collectionFile:\s*["']([^"']+)["']/g)];
      return Array.from(new Set(matches.map((m) => m[1])));
    } catch { return []; }
  })();
  const allFiles = Array.from(new Set([...files, ...referenced.filter((f) => fs.existsSync(path.join(DATA_DIR, f)))]));
  allFiles.sort();

  console.log(`Scanning ${allFiles.length} JSON files in ${DATA_DIR}`);

  const out = fs.createWriteStream(OUT_SQL, { flags: 'w' });
  out.write('-- Auto-generated by scripts/build-d1-index.mjs.  Re-run to refresh.\n');
  // Note: D1 remote API rejects BEGIN/COMMIT/PRAGMA — wrangler manages
  // its own transactions. Just emit DELETE + INSERTs as plain statements.
  out.write('DELETE FROM artworks;\n'); // wipe existing rows on reseed (FTS triggers cascade)

  let total = 0;
  let written = 0;
  let batch = [];

  const flushBatch = () => {
    if (!batch.length) return;
    const cols = '(id, name, artist, museum, exhibition_id, image, date, source_url, category)';
    const values = batch.map((r) => '(' +
      escapeSqlString(r.id) + ',' +
      escapeSqlString(r.name) + ',' +
      escapeSqlString(r.artist) + ',' +
      escapeSqlString(r.museum) + ',' +
      escapeSqlString(r.exhibition_id) + ',' +
      escapeSqlString(r.image) + ',' +
      escapeSqlString(r.date) + ',' +
      escapeSqlString(r.source_url) + ',' +
      escapeSqlString(r.category) + ')'
    ).join(',\n');
    out.write(`INSERT OR REPLACE INTO artworks ${cols} VALUES\n${values};\n`);
    written += batch.length;
    batch = [];
  };

  const seenIds = new Set();
  for (const file of allFiles) {
    const rows = loadCollection(path.join(DATA_DIR, file));
    for (const row of rows) {
      if (!row.id) continue;
      if (seenIds.has(row.id)) continue; // dedupe across files (same artwork referenced twice)
      seenIds.add(row.id);
      batch.push(row);
      total++;
      if (batch.length >= BATCH) flushBatch();
    }
    if (rows.length) console.log(`  ${file}: ${rows.length} entries`);
  }
  flushBatch();

  out.end();
  console.log(`\nWrote ${OUT_SQL}`);
  console.log(`Total: ${total} unique artworks (${written} insert rows)`);
  console.log(`\nNext steps:`);
  console.log(`  1. cd workers/semantic-search`);
  console.log(`  2. npx wrangler d1 create armin-text-search   # one-time, copy database_id into wrangler.toml`);
  console.log(`  3. npx wrangler d1 execute armin-text-search --remote --file=./schema.sql`);
  console.log(`  4. npx wrangler d1 execute armin-text-search --remote --file=./d1-seed.sql   # 5-15 min`);
  console.log(`  5. npx wrangler deploy`);
}

main();
