// Extract slug from sourceUrl
function getSlug(sourceUrl) {
    if (!sourceUrl) return null;
    const parts = sourceUrl.split('/');
    return parts[parts.length - 1];
}

// Split artworks
const pittiArtworks = [];
const uffiziArtworks = [];

for (const artwork of allObjects) {
    const slug = getSlug(artwork.sourceUrl);
    if (slug && PITTI_SLUGS.has(slug)) {
        pittiArtworks.push(artwork);
    } else {
        uffiziArtworks.push(artwork);
    }
}

