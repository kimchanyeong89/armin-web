const src = readFileSync(FILE, "utf8");

// Pre-scan: which ids already have description_ko / name_ko (idempotency guard).
const hasDescKo = new Set();
const hasNameKo = new Set();
{
  const blocks = src.split(/^ {4}id:\s*["']/m);
  for (let i = 1; i < blocks.length; i++) {
    const b = blocks[i];
    const id = b.match(/^([^"']+)["']/)[1];
    if (/\n {4}description_ko:/.test(b)) hasDescKo.add(id);
    if (/\n {4}name_ko:/.test(b)) hasNameKo.add(id);
  }
}

const lines = src.split("\n");
const out = [];
const done = new Set();
const idRe = /^( {4})id:\s*["']([^"']+)["'],?\s*$/;

for (const line of lines) {
  out.push(line);
  const m = line.match(idRe);
  if (!m) continue;
  const id = m[2];
  if (done.has(id)) continue;
  if (!DESC_KO[id]) continue;
  if (hasDescKo.has(id)) continue; // already inserted on a prior run
  done.add(id);
  if (NAME_KO_ADD[id] && !hasNameKo.has(id)) {
    out.push(`    name_ko: ${JSON.stringify(NAME_KO_ADD[id])},`);
  }
  out.push(`    description_ko: ${JSON.stringify(DESC_KO[id])},`);
}

const missing = Object.keys(DESC_KO).filter((id) => !done.has(id) && !hasDescKo.has(id));
